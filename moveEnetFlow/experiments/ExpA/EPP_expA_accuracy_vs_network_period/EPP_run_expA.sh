#!/usr/bin/env bash
set -Eeuo pipefail

# Experiment A for the current EventPointPose rolling-FIFO pipeline on DHP19.
#
# For every selected ch2dvs/ch3dvs recording and every network period, this
# script runs eventPointPose_offline and writes:
#   - the held-pose prediction CSV;
#   - the C++ runner log;
#   - the Python YARP sidecar log;
#   - optional NumPy debug dumps.
#
# The Python sidecar owns the persistent sliding FIFO. The C++ runner sends
# only the events accumulated since the previous network request; the sidecar
# appends them to the FIFO, retains the most recent 7500 events, applies
# RasEPC, samples 2048 points, and runs PointNet.
#
# The output naming keeps the historical "net_flow" tag so existing ExpA
# notebooks and directory conventions do not need to change.

EXP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RESULTS_ROOT="${MOVENET_RESULTS_ROOT:-/data/MovEnet_OFK_results}"
RESULT_DIR="$RESULTS_ROOT/EPP_dhp19_full_test"

# -----------------------------------------------------------------------------
# Defaults
# -----------------------------------------------------------------------------
BINARY="/workspace/moveEnetFlow/build2/eventPointPose_offline"

DATA_FILE=""
DATA_ROOT="/data/dhp19_testing_set_S13toS17"
DATA_GLOB="*/ch[23]dvs/data.log"

MODEL_PATH="/workspace/model_mounts/eventpointpose/PointNet/models/model.pth"
EPP_SCRIPT="/workspace/model_mounts/eventpointpose/PointNet/models/eventPointPose_yarp_server.py"

RAW_DIR="$RESULT_DIR/results/raw"
LOG_DIR="$RESULT_DIR/results/logs"
DUMP_ROOT=""

# 100, 50, 20, 10, 5 and 2 Hz.
# NETWORK_PERIODS=("0.01" "0.02" "0.05" "0.1" "0.2" "0.5")
NETWORK_PERIODS=("0.02")
# to do again np 0.02
OUTPUT_PERIOD="0.005"

DEVICE="cuda:0"
IMG_W="346"
IMG_H="260"
FIFO_SIZE="7500"
NUM_POINTS="2048"
SEED="1"

# The DHP19 data.log files used here were generated by the standard hpe-core
# preprocessing, so hot-pixel, background and IR filters must not run again.
INPUT_PREPROCESSING="already_filtered"

STARTUP_TIMEOUT="30"
RESPONSE_TIMEOUT="0"       # 0 = wait indefinitely for a response
SERVER_VERBOSE="false"
DUMP_FIRST_N="1"

# Debug-only input truncation. This is implemented by the shell because the
# current rolling-FIFO C++ runner has no --max_packets option.
MAX_PACKETS="-1"
SKIP_EXISTING="false"
SKIP_SERVER_CHECK="false"

usage() {
  cat <<USAGE
Usage: $(basename "$0") [options]

DHP19 paths:
  --binary <path>                 eventPointPose_offline executable
  --data_root <path>              DHP19 root containing sequence directories
  --data_file <path>              Run one ch2dvs/ch3dvs data.log only
  --data_glob <pattern>           find -path pattern under data_root
                                  Default: */ch[23]dvs/data.log
  --model_path <path>             PointNet checkpoint
  --checkpoint_path <path>        Legacy alias for --model_path
  --epp_script <path>             Rolling-FIFO Python YARP sidecar
  --raw_dir <path>                Raw prediction CSV root
  --log_dir <path>                C++ and Python log directory
  --dump_root <path>              Optional root for NumPy validation dumps

Timing:
  --network_periods <list>        Comma-separated periods
                                  Default: 0.01,0.02,0.05,0.1,0.2,0.5
  --periods <list>                Alias for --network_periods
  --net_period <seconds>          Run one network period only
  --output_period <seconds>       Held-pose CSV period. Default: 0.005

EventPointPose:
  --device <device>               cpu, cuda:N, or N. Default: cuda:0
  --w <int>                       Sensor width. Required by model: 346
  --h <int>                       Sensor height. Required by model: 260
  --fifo_size <int>               Persistent rolling FIFO. Required: 7500
  --raw_events_per_window <int>   Legacy alias for --fifo_size
  --num_points <int>              Post-RasEPC point count. Required: 2048
  --seed <int>                    NumPy/PyTorch seed. Default: 1

Sidecar / debug:
  --startup_timeout <seconds>     Sidecar startup timeout. Default: 30
  --response_timeout <seconds>    Per-request timeout; 0 blocks. Default: 0
  --server_verbose                Log every server request
  --dump_first_n <int>            Successful inferences dumped per run
  --max_packets <int>             Use only the first N packet lines; -1 = full
  --skip_existing                 Skip a run when its prediction CSV is nonempty
  --skip_server_check             Do not inspect the sidecar source for FIFO markers

Other:
  --help                          Show this help

Unsupported legacy options:
  The current C++ runner does not expose --gpu_file, --gpu_period_ms,
  --gpu_index, --pwrjlr_file, --no_video, or --swap_lr. They are not passed.
USAGE
}

split_csv_into_array() {
  local csv="$1"
  local -n destination="$2"
  IFS=',' read -r -a destination <<< "$csv"
}

is_positive_number() {
  awk -v value="$1" 'BEGIN { exit !(value + 0 > 0) }'
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --binary) BINARY="$2"; shift 2 ;;
    --data_root) DATA_ROOT="$2"; shift 2 ;;
    --data_file) DATA_FILE="$2"; shift 2 ;;
    --data_glob) DATA_GLOB="$2"; shift 2 ;;
    --model_path|--checkpoint_path) MODEL_PATH="$2"; shift 2 ;;
    --epp_script) EPP_SCRIPT="$2"; shift 2 ;;
    --raw_dir) RAW_DIR="$2"; shift 2 ;;
    --log_dir) LOG_DIR="$2"; shift 2 ;;
    --dump_root) DUMP_ROOT="$2"; shift 2 ;;

    --network_periods|--periods)
      split_csv_into_array "$2" NETWORK_PERIODS
      shift 2
      ;;
    --net_period) NETWORK_PERIODS=("$2"); shift 2 ;;
    --output_period) OUTPUT_PERIOD="$2"; shift 2 ;;

    --device) DEVICE="$2"; shift 2 ;;
    --w) IMG_W="$2"; shift 2 ;;
    --h) IMG_H="$2"; shift 2 ;;
    --fifo_size|--raw_events_per_window) FIFO_SIZE="$2"; shift 2 ;;
    --num_points) NUM_POINTS="$2"; shift 2 ;;
    --seed) SEED="$2"; shift 2 ;;

    --startup_timeout) STARTUP_TIMEOUT="$2"; shift 2 ;;
    --response_timeout) RESPONSE_TIMEOUT="$2"; shift 2 ;;
    --server_verbose) SERVER_VERBOSE="true"; shift ;;
    --dump_first_n) DUMP_FIRST_N="$2"; shift 2 ;;
    --max_packets) MAX_PACKETS="$2"; shift 2 ;;
    --skip_existing) SKIP_EXISTING="true"; shift ;;
    --skip_server_check) SKIP_SERVER_CHECK="true"; shift ;;

    --gpu_file|--gpu_period_ms|--gpu_index|--pwrjlr_file|--pwrjlr_dir|--swap_lr|--no_video)
      echo "Option $1 belongs to an older runner and is not supported by the current rolling-FIFO C++ executable." >&2
      exit 2
      ;;

    --help) usage; exit 0 ;;
    *)
      echo "Unknown option: $1" >&2
      usage >&2
      exit 1
      ;;
  esac
done

# -----------------------------------------------------------------------------
# Validation
# -----------------------------------------------------------------------------
if [[ ! -x "$BINARY" ]]; then
  echo "Binary not found or not executable: $BINARY" >&2
  exit 1
fi
if [[ ! -f "$MODEL_PATH" ]]; then
  echo "Checkpoint not found: $MODEL_PATH" >&2
  exit 1
fi
if [[ ! -f "$EPP_SCRIPT" ]]; then
  echo "EventPointPose sidecar not found: $EPP_SCRIPT" >&2
  exit 1
fi
if [[ -n "$DATA_FILE" && ! -f "$DATA_FILE" ]]; then
  echo "Data file not found: $DATA_FILE" >&2
  exit 1
fi
if [[ -z "$DATA_FILE" && ! -d "$DATA_ROOT" ]]; then
  echo "Data root not found: $DATA_ROOT" >&2
  exit 1
fi
if [[ ${#NETWORK_PERIODS[@]} -eq 0 ]]; then
  echo "No network periods were specified." >&2
  exit 1
fi
if ! is_positive_number "$OUTPUT_PERIOD"; then
  echo "--output_period must be positive: $OUTPUT_PERIOD" >&2
  exit 1
fi
for period in "${NETWORK_PERIODS[@]}"; do
  if ! is_positive_number "$period"; then
    echo "Every network period must be positive. Invalid value: $period" >&2
    exit 1
  fi
done

if [[ "$IMG_W" != "346" || "$IMG_H" != "260" ]]; then
  echo "The current PointNet checkpoint requires --w 346 --h 260." >&2
  exit 1
fi
if [[ "$FIFO_SIZE" != "7500" ]]; then
  echo "The current rolling pipeline requires --fifo_size 7500." >&2
  exit 1
fi
if [[ "$NUM_POINTS" != "2048" ]]; then
  echo "The current PointNet checkpoint requires --num_points 2048." >&2
  exit 1
fi
if [[ ! "$MAX_PACKETS" =~ ^-?[0-9]+$ ]] || (( MAX_PACKETS == 0 || MAX_PACKETS < -1 )); then
  echo "--max_packets must be -1 or a positive integer." >&2
  exit 1
fi
if [[ ! "$DUMP_FIRST_N" =~ ^[0-9]+$ ]]; then
  echo "--dump_first_n must be a non-negative integer." >&2
  exit 1
fi

if command -v yarp >/dev/null 2>&1 && ! yarp where >/dev/null 2>&1; then
  echo "YARP name server is unavailable. Start yarpserver before running the experiment." >&2
  exit 1
fi

# Verify that the executable exposes the current rolling-FIFO CLI names.
BINARY_HELP="$("$BINARY" --help 2>&1 || true)"
for required_option in --model_path --EventPointPose_script --fifo_size --server_log; do
  if ! grep -q -- "$required_option" <<< "$BINARY_HELP"; then
    echo "The selected binary does not expose $required_option and does not match the current rolling-FIFO runner:" >&2
    echo "  $BINARY" >&2
    exit 1
  fi
done

# Avoid accidentally running the later independent-period sidecar with the
# rolling-FIFO C++ client. This is a source-level sanity check, not a model test.
if [[ "$SKIP_SERVER_CHECK" != "true" ]]; then
  if ! grep -qE 'class[[:space:]]+EventFIFO|self\.fifo[[:space:]]*=' "$EPP_SCRIPT" || \
     ! grep -q 'WARMUP' "$EPP_SCRIPT"; then
    echo "The selected Python sidecar does not look like the persistent rolling-FIFO version:" >&2
    echo "  $EPP_SCRIPT" >&2
    echo "Expected EventFIFO/self.fifo and WARMUP markers." >&2
    echo "Use --skip_server_check only after manually verifying the server." >&2
    exit 1
  fi
  if grep -q 'INSUFFICIENT_BATCH' "$EPP_SCRIPT"; then
    echo "The selected Python sidecar contains INSUFFICIENT_BATCH and appears to be the independent-period version, not rolling FIFO:" >&2
    echo "  $EPP_SCRIPT" >&2
    exit 1
  fi
fi

mkdir -p "$RAW_DIR" "$LOG_DIR"
if [[ -n "$DUMP_ROOT" ]]; then
  mkdir -p "$DUMP_ROOT"
fi

# -----------------------------------------------------------------------------
# Input discovery
# -----------------------------------------------------------------------------
declare -a LOG_FILES=()
if [[ -n "$DATA_FILE" ]]; then
  LOG_FILES+=("$(realpath -s "$DATA_FILE")")
else
  mapfile -t LOG_FILES < <(find "$DATA_ROOT" -type f -path "$DATA_GLOB" | sort)
fi

if [[ ${#LOG_FILES[@]} -eq 0 ]]; then
  echo "No input files found with pattern: $DATA_GLOB" >&2
  exit 1
fi

make_rel_stem() {
  local log_file="$1"
  local rel_path

  if [[ -n "$DATA_FILE" ]]; then
    rel_path="$(basename "$(dirname "$(dirname "$log_file")")")/$(basename "$(dirname "$log_file")")"
  else
    rel_path="$(realpath --relative-to="$DATA_ROOT" "$log_file")"
    rel_path="${rel_path%/data.log}"
  fi

  rel_path="${rel_path//\//__}"
  rel_path="${rel_path// /_}"
  printf '%s\n' "$rel_path"
}

camera_from_path() {
  local channel_dir
  channel_dir="$(basename "$(dirname "$1")")"
  case "$channel_dir" in
    ch2dvs) printf '2\n' ;;
    ch3dvs) printf '3\n' ;;
    *)
      echo "Unsupported EventPointPose input channel: $channel_dir" >&2
      return 1
      ;;
  esac
}

# Optional packet truncation is cached once per source file and reused across
# all network-period runs.
TMP_ROOT=""
declare -A PREPARED_INPUTS=()
cleanup() {
  if [[ -n "$TMP_ROOT" && -d "$TMP_ROOT" ]]; then
    rm -rf "$TMP_ROOT"
  fi
}
on_signal() {
  cleanup
  exit 130
}
trap cleanup EXIT
trap on_signal INT TERM

PREPARED_INPUT=""
prepare_input() {
  local source="$1"

  if (( MAX_PACKETS < 0 )); then
    PREPARED_INPUT="$source"
    return
  fi

  if [[ -z "$TMP_ROOT" ]]; then
    TMP_ROOT="$(mktemp -d /tmp/epp_expA_packets.XXXXXX)"
  fi

  if [[ -z "${PREPARED_INPUTS[$source]+present}" ]]; then
    local stem target
    stem="$(make_rel_stem "$source")"
    target="$TMP_ROOT/${stem}_first_${MAX_PACKETS}_packets.log"
    head -n "$MAX_PACKETS" "$source" > "$target"
    PREPARED_INPUTS["$source"]="$target"
  fi

  PREPARED_INPUT="${PREPARED_INPUTS[$source]}"
}

# Validate every discovered input now rather than halfway through the sweep.
for log_file in "${LOG_FILES[@]}"; do
  if [[ ! -f "$log_file" ]]; then
    echo "Input disappeared or is not a file: $log_file" >&2
    exit 1
  fi
  camera_from_path "$log_file" >/dev/null
done

# -----------------------------------------------------------------------------
# Summary
# -----------------------------------------------------------------------------
echo "Experiment A: DHP19 EventPointPose rolling FIFO vs network_period"
echo "Binary               : $BINARY"
echo "Checkpoint           : $MODEL_PATH"
echo "EPP sidecar          : $EPP_SCRIPT"
echo "Pipeline             : persistent sliding FIFO"
echo "Input preprocessing  : $INPUT_PREPROCESSING"
echo "Device               : $DEVICE"
echo "Image size           : ${IMG_W}x${IMG_H}"
echo "FIFO / RasEPC points : $FIFO_SIZE / $NUM_POINTS"
echo "Seed                 : $SEED"
if [[ -n "$DATA_FILE" ]]; then
  echo "Data mode            : single file"
  echo "Data file            : ${LOG_FILES[0]}"
else
  echo "Data mode            : full dataset"
  echo "Data root            : $DATA_ROOT"
  echo "Data glob            : $DATA_GLOB"
fi
echo "Network periods      : ${NETWORK_PERIODS[*]}"
echo "Output period        : $OUTPUT_PERIOD"
echo "Startup timeout      : $STARTUP_TIMEOUT"
echo "Response timeout     : $RESPONSE_TIMEOUT"
echo "Server verbose       : $SERVER_VERBOSE"
echo "Max packet lines     : $MAX_PACKETS"
echo "Raw CSV root         : $RAW_DIR"
echo "Log directory        : $LOG_DIR"
echo "Dump root            : ${DUMP_ROOT:-disabled}"
echo "Sequences/cameras    : ${#LOG_FILES[@]}"

# -----------------------------------------------------------------------------
# Main sweep
# -----------------------------------------------------------------------------
for network_period in "${NETWORK_PERIODS[@]}"; do
  safe_period="${network_period//./p}"
  run_dir="$RAW_DIR/np_${safe_period}"
  mkdir -p "$run_dir"

  detection_rate="$(awk -v period="$network_period" 'BEGIN { printf "%.3f", 1.0 / period }')"
  echo
  echo "[network_period=${network_period}s (${detection_rate} Hz)]"

  for source_log in "${LOG_FILES[@]}"; do
    rel_stem="$(make_rel_stem "$source_log")"
    camera="$(camera_from_path "$source_log")"
    prepare_input "$source_log"
    run_input="$PREPARED_INPUT"

    output_csv="$run_dir/${rel_stem}_net_flow_np_${safe_period}.csv"
    run_log="$LOG_DIR/${rel_stem}_net_flow_np_${safe_period}.log"
    server_log="$LOG_DIR/${rel_stem}_net_flow_np_${safe_period}_server.log"

    if [[ "$SKIP_EXISTING" == "true" && -f "$output_csv" ]] && \
       (( $(wc -l < "$output_csv") > 1 )); then
      echo "  -> [$rel_stem] skip: prediction CSV already contains data"
      continue
    fi

    common_args=(
      --data_file "$run_input"
      --camera "$camera"
      --output_period "$OUTPUT_PERIOD"
      --net_period "$network_period"
      --w "$IMG_W"
      --h "$IMG_H"
      --model_path "$MODEL_PATH"
      --EventPointPose_script "$EPP_SCRIPT"
      --fifo_size "$FIFO_SIZE"
      --num_points "$NUM_POINTS"
      --seed "$SEED"
      --device "$DEVICE"
      --input_preprocessing "$INPUT_PREPROCESSING"
      --startup_timeout "$STARTUP_TIMEOUT"
      --response_timeout "$RESPONSE_TIMEOUT"
      --server_log "$server_log"
      --output_csv "$output_csv"
    )

    if [[ "$SERVER_VERBOSE" == "true" ]]; then
      common_args+=(--server_verbose)
    fi

    if [[ -n "$DUMP_ROOT" ]]; then
      dump_dir="$DUMP_ROOT/np_${safe_period}/${rel_stem}"
      mkdir -p "$dump_dir"
      common_args+=(--dump_dir "$dump_dir" --dump_first_n "$DUMP_FIRST_N")
    fi

    echo "  -> [$rel_stem] camera=$camera"

    if ! PYTHONUNBUFFERED=1 "$BINARY" "${common_args[@]}" > "$run_log" 2>&1; then
      echo "Run failed: $rel_stem, network_period=$network_period" >&2
      echo "C++ log   : $run_log" >&2
      echo "Server log: $server_log" >&2
      tail -n 60 "$run_log" >&2 || true
      exit 1
    fi

    if ! grep -q "Valid PointNet inferences:" "$run_log"; then
      echo "Run completed without the expected final statistics: $run_log" >&2
      exit 1
    fi

    valid_inferences="$(grep "Valid PointNet inferences:" "$run_log" | tail -n 1 | sed -E 's/.*:[[:space:]]*//')"
    warmup_responses="$(grep "Warm-up responses:" "$run_log" | tail -n 1 | sed -E 's/.*:[[:space:]]*//' || true)"
    csv_rows="$(grep "CSV rows written:" "$run_log" | tail -n 1 | sed -E 's/.*:[[:space:]]*//' || true)"

    echo "     valid_inferences=${valid_inferences:-unknown} warmup=${warmup_responses:-unknown} csv_rows=${csv_rows:-unknown}"
  done
done

echo
echo "Experiment completed."
echo "Prediction CSV files : $RAW_DIR"
echo "C++/server logs      : $LOG_DIR"
if [[ -n "$DUMP_ROOT" ]]; then
  echo "Validation dumps     : $DUMP_ROOT"
fi