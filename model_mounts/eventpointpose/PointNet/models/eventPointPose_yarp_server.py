def main() -> int:
    args = build_parser().parse_args()

    ran_self_test = False
    if args.self_test_all or args.self_test_coordinates:
        run_coordinate_self_test()
        ran_self_test = True
    if args.self_test_all or args.self_test_rasepc:
        run_rasepc_self_test(args.upstream_repo)
        ran_self_test = True
    if ran_self_test:
        return 0

    # Backward-compatible alias used by an earlier draft of this sidecar.
    if args.input_preprocessing == "preprocessed":
        args.input_preprocessing = "already_filtered"

    if args.w != SENSOR_WIDTH or args.h != SENSOR_HEIGHT:
        raise SystemExit(
            f"The supplied MeanLabel checkpoint requires {SENSOR_WIDTH}x{SENSOR_HEIGHT}; "
            f"received {args.w}x{args.h}"
        )
    if args.fifo_size != FIFO_SIZE:
        raise SystemExit(f"This deployment requires fifo_size={FIFO_SIZE}")
    if args.num_points != POINTNET_POINTS:
        raise SystemExit(f"The supplied checkpoint requires num_points={POINTNET_POINTS}")
    if args.rasepc_channels != RASEPC_CHANNELS:
        raise SystemExit(f"EventPointPose RasEPC requires {RASEPC_CHANNELS} temporal channels")
    if args.input_preprocessing == "raw" and not args.hotpixel_path:
        raise SystemExit("--hotpixel_path is required with --input_preprocessing raw")
    if yarp is None:
        raise SystemExit("Could not import yarp. Enable the YARP Python bindings.")

    yarp.Network.init()
    if not yarp.Network.checkNetwork(2.0):
        raise SystemExit("YARP server is unavailable. Start yarpserver first.")

    engine = EventPointPoseEngine(args)

    in_port = yarp.BufferedPortBottle()
    out_port = yarp.BufferedPortBottle()
    if not in_port.open(args.event_port):
        raise SystemExit(f"Could not open event input port: {args.event_port}")
    if not out_port.open(args.sklt_port):
        in_port.close()
        raise SystemExit(f"Could not open skeleton output port: {args.sklt_port}")

    stop_requested = False

    def request_stop(_signum, _frame) -> None:
        nonlocal stop_requested
        stop_requested = True
        try:
            in_port.interrupt()
        except Exception:
            pass

    signal.signal(signal.SIGINT, request_stop)
    signal.signal(signal.SIGTERM, request_stop)

    print(
        "EventPointPose server ready: "
        f"device={engine.device}, input_preprocessing={args.input_preprocessing}, "
        f"background_domain={args.background_domain}, seed={args.seed}",
        flush=True,
    )

    try:
        while not stop_requested:
            request = in_port.read(True)
            if request is None:
                if stop_requested:
                    break
                continue

            request_id = -999
            request_ts = 0.0
            try:
                request_id, request_ts, camera, events = parse_request(request)
                if request_id < 0:
                    write_reply(
                        out_port,
                        request_ts,
                        request_id,
                        "SHUTDOWN",
                        np.zeros((NUM_JOINTS, 2), dtype=np.float32),
                        np.zeros(NUM_JOINTS, dtype=np.float32),
                        [0, len(engine.fifo), 0, 0.0],
                    )
                    break
                if camera not in (2, 3):
                    raise ValueError(
                        f"PointNet MeanLabel deployment supports DHP19 camera 2 or 3, got {camera}"
                    )

                status, xy, conf, diagnostics = engine.process_request(
                    request_id=request_id,
                    camera=camera,
                    events=events,
                )
                write_reply(
                    out_port,
                    request_ts,
                    request_id,
                    status,
                    xy,
                    conf,
                    diagnostics,
                )
                if args.verbose or status != "OK":
                    print(
                        "EventPointPose request "
                        f"id={request_id} ts={request_ts:.6f} camera={camera} "
                        f"input={events.shape[0]} accepted={int(diagnostics[0])} "
                        f"fifo={int(diagnostics[1])} rasepc={int(diagnostics[2])} "
                        f"status={status}",
                        flush=True,
                    )
            except Exception as exc:
                print(
                    f"EventPointPose request {request_id} failed: {type(exc).__name__}: {exc}",
                    file=sys.stderr,
                    flush=True,
                )
                write_reply(
                    out_port,
                    request_ts,
                    request_id,
                    "ERROR",
                    np.zeros((NUM_JOINTS, 2), dtype=np.float32),
                    np.zeros(NUM_JOINTS, dtype=np.float32),
                    [0, len(engine.fifo), 0, 0.0],
                    message=f"{type(exc).__name__}: {exc}",
                )
    finally:
        in_port.close()
        out_port.close()
        yarp.Network.fini()

    return 0


if __name__ == "__main__":
    sys.exit(main())
