#!/usr/bin/env python3
"""
YARP sidecar for MasterHow/EventPointPose PointNet (DHP19 MeanLabel checkpoint).

Default deployment mode
-----------------------
The input ``data.log`` files are assumed to have been generated by the standard
hpe-core DHP19 preprocessing/export pipeline. Therefore hot-pixel filtering,
background filtering, and the two IR masks have already been applied and are
skipped by default (``--input_preprocessing already_filtered``).

Request Bottle (C++ -> Python)
------------------------------
    bottle[0] : int32 request id
    bottle[1] : float64 inference timestamp (seconds)
    bottle[2] : int32 camera id
    bottle[3] : flat list of events [x, y, packet_timestamp, polarity, ...]

The event coordinates in a preprocessed hpe-core log are local, zero-based,
and already flipped by the DHP19 preprocessing/export path. Before RasEPC they
are converted back to the exact MeanLabel point-cloud representation used by
EventPointPose:

    x_epp = x_log + 1
    y_epp = (sensor_height - 1) - y_log

RasEPC itself then performs the repository's own ``int() - 1`` indexing.

Reply Bottle (Python -> C++)
----------------------------
The reply remains compatible with hpe-core::extractSkeletonFromYARP():
    bottle[0] : float64 inference timestamp
    bottle[1] : list of 39 floats
                  26 coordinates: x0,y0,...,x12,y12
                  13 confidences (1.0 for a valid EventPointPose prediction)
    bottle[2] : string status: OK, WARMUP, NO_UPDATE, ERROR, SHUTDOWN
    bottle[3] : int32 request id
    bottle[4] : diagnostic list
                  accepted_events, fifo_size, rasepc_points, inference_ms
    bottle[5] : optional diagnostic/error message

The FIFO is persistent and contains at most the 7500 most recent accepted
input events. A new PointNet inference is executed only when the current batch
adds at least one event and the FIFO is full.
"""

